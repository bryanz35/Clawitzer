// hardware/urdf/arm.urdf → firmware/arm-controller/include/arm_config.h
// Run: npm run gen:arm-config. Fails loudly (non-zero exit) on anything missing or unsupported.
// Uses the same URDF reader as the IK (loadArm), so firmware and client limits can't disagree.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { NUM_JOINTS } from "@arm-mirror/protocol";
import { DEG, loadArm } from "@arm-mirror/kinematics";

const URDF_PATH = fileURLToPath(new URL("../hardware/urdf/arm.urdf", import.meta.url));
const OUT_PATH = fileURLToPath(new URL("../firmware/arm-controller/include/arm_config.h", import.meta.url));

function main(): void {
  const model = loadArm(readFileSync(URDF_PATH, "utf8"));
  const n = model.names.length;
  if (n !== NUM_JOINTS) throw new Error(`found ${n} movable joints, protocol expects NUM_JOINTS = ${NUM_JOINTS}`);

  const f = (rad: number[]) => rad.map((x) => `${(x * DEG).toFixed(3)}f`).join(", ");
  const lim = model.limits;
  const header = `// GENERATED by tools/gen-arm-config.ts — do not edit
// Source: hardware/urdf/arm.urdf. Regenerate with \`npm run gen:arm-config\`.
// Units: degrees, deg/s, deg/s². These are the ONLY joint limits the firmware uses.
#pragma once

#define ARM_NUM_JOINTS ${n}

static const char* const ARM_JOINT_NAMES[ARM_NUM_JOINTS] = {${model.names.map((s) => `"${s}"`).join(", ")}};
static const float ARM_JOINT_MIN_DEG[ARM_NUM_JOINTS] = {${f(lim.map((l) => l.lower))}};
static const float ARM_JOINT_MAX_DEG[ARM_NUM_JOINTS] = {${f(lim.map((l) => l.upper))}};
static const float ARM_JOINT_MAX_VEL_DEG_S[ARM_NUM_JOINTS] = {${f(lim.map((l) => l.velocity))}};
static const float ARM_JOINT_MAX_ACCEL_DEG_S2[ARM_NUM_JOINTS] = {${f(lim.map((l) => l.acceleration))}};
static const float ARM_HOME_DEG[ARM_NUM_JOINTS] = {${f(model.restPose)}};
static const float ARM_PARK_DEG[ARM_NUM_JOINTS] = {${f(model.parkPose)}};
`;
  writeFileSync(OUT_PATH, header);
  console.log(`wrote ${OUT_PATH} (${n} joints: ${model.names.join(", ")})`);
}

try {
  main();
} catch (e) {
  console.error(`gen-arm-config: ${e instanceof Error ? e.message : e}`);
  process.exit(1);
}
